def pix(b,p): return ((b>>(7-p))&1)|(((b>>(3-p))&1)<<1)
def screen(ram,pal,rows=23,width=64):
    im=Image.new('RGB',(width*4,rows*8))
    for y in range(rows*8):
        a=0xC000+(y//8)*64+(y%8)*0x800
        for bx in range(width):
            b=ram[a+bx]
            for p in range(4): im.putpixel((bx*4+p,y),HW[pal[pix(b,p)]&31])
    return im
