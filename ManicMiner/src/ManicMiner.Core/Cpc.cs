namespace ManicMiner.Core;

public static class Cpc
{
    public const int Width = 256, Height = 184;

    /// <summary>Hardware ink number (0..31) to 0xRRGGBB.</summary>
    public static readonly uint[] Hw = { 0x808080, 0x808080, 0x00FF80, 0xFFFF80, 0x000080, 0xFF0080, 0x008080, 0xFF8080, 0xFF0080, 0xFFFF80, 0xFFFF00, 0xFFFFFF, 0xFF0000, 0xFF00FF, 0xFF8000, 0xFF80FF, 0x000080, 0x00FF80, 0x00FF00, 0x00FFFF, 0x000000, 0x0000FF, 0x008000, 0x0080FF, 0x800080, 0x80FF80, 0x80FF00, 0x80FFFF, 0x800000, 0x8000FF, 0x808000, 0x8080FF };

    /// <summary>Firmware ink (0..26) to hardware ink number.</summary>
    public static readonly byte[] FwToHw =
    { 0x14,0x04,0x15,0x1C,0x18,0x1D,0x0C,0x05,0x0D,0x16,0x06,0x17,0x1E,0x00,0x1F,0x0E,0x07,0x0F,0x12,0x02,0x13,0x1A,0x19,0x1B,0x0A,0x03,0x0B };

    public static int ScreenAddr(int y) => 0xC000 + (y >> 3) * 64 + (y & 7) * 0x800;

    public static int Pixel(byte b, int p) => ((b >> (7 - p)) & 1) | (((b >> (3 - p)) & 1) << 1);
}
